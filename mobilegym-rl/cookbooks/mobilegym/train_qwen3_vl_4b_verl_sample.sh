#!/usr/bin/env bash
set -euo pipefail

# Sampling-focused variant of train_qwen3_vl_4b_verl.sh.
# Override any of these from the environment when running a follow-up trial.
SAMPLE_N="${SAMPLE_N:-1}"
SAMPLE_TEMPLATES="${SAMPLE_TEMPLATES:-true}"
TASK_SEED="${TASK_SEED:-43}"
DYNAMIC_SAMPLING="${DYNAMIC_SAMPLING:-true}"
DYNAMIC_TARGET_GROUPS="${DYNAMIC_TARGET_GROUPS:-12}"
DYNAMIC_MAX_ROUNDS="${DYNAMIC_MAX_ROUNDS:-8}"
DYNAMIC_MIN_REWARD_RANGE="${DYNAMIC_MIN_REWARD_RANGE:-1e-6}"
REJECTION_MULTIPLIER="${REJECTION_MULTIPLIER:-1}"
TRAIN_BATCH_SIZE="${TRAIN_BATCH_SIZE:-12}"
PPO_MINI_BATCH_SIZE="${PPO_MINI_BATCH_SIZE:-$TRAIN_BATCH_SIZE}"
ROLLOUT_N="${ROLLOUT_N:-8}"
GEN_BATCH_SIZE="${GEN_BATCH_SIZE:-16}"
ENV_POOL_SIZE="${ENV_POOL_SIZE:-$((GEN_BATCH_SIZE * ROLLOUT_N))}"
ENV_NUM_BROWSERS="${ENV_NUM_BROWSERS:-8}"
ENV_INIT_BATCH_SIZE="${ENV_INIT_BATCH_SIZE:-8}"
ENV_INIT_WARMUP="${ENV_INIT_WARMUP:-true}"
USE_KL_LOSS="${USE_KL_LOSS:-false}"
USE_KL_IN_REWARD="${USE_KL_IN_REWARD:-false}"
EXPERIMENT_NAME="${EXPERIMENT_NAME:-mobilegym-qwen3-vl-4b-train-SAMPLE-N1-DYNAMIC}"

export SAMPLE_N
export SAMPLE_TEMPLATES
export TASK_SEED
export EXPERIMENT_NAME
export DYNAMIC_SAMPLING
export DYNAMIC_TARGET_GROUPS
export DYNAMIC_MAX_ROUNDS
export DYNAMIC_MIN_REWARD_RANGE
export REJECTION_MULTIPLIER
export TRAIN_BATCH_SIZE
export PPO_MINI_BATCH_SIZE
export ROLLOUT_N
export GEN_BATCH_SIZE
export ENV_POOL_SIZE
export ENV_NUM_BROWSERS
export ENV_INIT_BATCH_SIZE
export ENV_INIT_WARMUP
export USE_KL_LOSS
export USE_KL_IN_REWARD

SCRIPT_DIR="$(dirname -- "$(realpath -- "${BASH_SOURCE[0]}")")"
exec bash "$SCRIPT_DIR/train_qwen3_vl_4b_verl.sh" "$@"
