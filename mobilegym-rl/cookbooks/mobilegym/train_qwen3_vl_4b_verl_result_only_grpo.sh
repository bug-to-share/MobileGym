#!/usr/bin/env bash
set -euo pipefail

# Sparse-result GRPO baseline:
# reward=1 only for strict success, otherwise reward=0.
SCRIPT_DIR="$(dirname -- "$(realpath -- "${BASH_SOURCE[0]}")")"

SAMPLE_N="${SAMPLE_N:-1}"
SAMPLE_TEMPLATES="${SAMPLE_TEMPLATES:-false}"
TASK_SEED="${TASK_SEED:-42}"
TRAIN_BATCH_SIZE="${TRAIN_BATCH_SIZE:-12}"
PPO_MINI_BATCH_SIZE="${PPO_MINI_BATCH_SIZE:-96}"
ROLLOUT_N="${ROLLOUT_N:-8}"
GEN_BATCH_SIZE="${GEN_BATCH_SIZE:-$TRAIN_BATCH_SIZE}"
ENV_POOL_SIZE="${ENV_POOL_SIZE:-$((GEN_BATCH_SIZE * ROLLOUT_N))}"
ENV_NUM_BROWSERS="${ENV_NUM_BROWSERS:-8}"
ENV_INIT_BATCH_SIZE="${ENV_INIT_BATCH_SIZE:-8}"
ENV_INIT_WARMUP="${ENV_INIT_WARMUP:-true}"
USE_KL_LOSS="${USE_KL_LOSS:-true}"
USE_KL_IN_REWARD="${USE_KL_IN_REWARD:-false}"
VAL_BEFORE_TRAIN="${VAL_BEFORE_TRAIN:-false}"
TEST_FREQ="${TEST_FREQ:-0}"
EXPERIMENT_NAME="${EXPERIMENT_NAME:-mobilegym-qwen3-vl-4b-train-RESULT-ONLY-GRPO}"

export MOBILEGYM_REWARD_MODE=result_only
export MOBILEGYM_FALSE_COMPLETE_MODE=legacy
export DYNAMIC_SAMPLING=false
export REJECTION_ENABLE=false
export REJECTION_MULTIPLIER=1
export SAMPLE_N SAMPLE_TEMPLATES TASK_SEED
export TRAIN_BATCH_SIZE PPO_MINI_BATCH_SIZE ROLLOUT_N GEN_BATCH_SIZE
export ENV_POOL_SIZE ENV_NUM_BROWSERS ENV_INIT_BATCH_SIZE ENV_INIT_WARMUP
export USE_KL_LOSS USE_KL_IN_REWARD VAL_BEFORE_TRAIN TEST_FREQ EXPERIMENT_NAME

exec bash "$SCRIPT_DIR/train_qwen3_vl_4b_verl.sh" "$@"
